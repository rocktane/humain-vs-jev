// Causes d'échec d'une analyse, transmises au front pour un message juste.
const (
	ReasonTimeout   = "timeout"   // délai JEV_TIMEOUT dépassé
	ReasonNetwork   = "network"   // TypeSafe injoignable
	ReasonAuth      = "auth"      // clé refusée ou accès aux images retiré (401, 403)
	ReasonQuota     = "quota"     // limite de débit ou crédit du compte (429, 402)
	ReasonServer    = "server"    // panne côté TypeSafe (5xx)
	ReasonRejected  = "rejected"  // requête refusée (autre 4xx)
	ReasonInvalid   = "invalid"   // réponse 200 inutilisable
	ReasonBudget    = "budget"    // quota quotidien du serveur atteint, aucun appel lancé
	ReasonCancelled = "cancelled" // partie abandonnée
)

// JevError classe une erreur d'analyse. Le corps de la réponse n'y figure jamais.
type JevError struct {
	Reason string
	Status int
	Err    error
}

func (e *JevError) Error() string {
	if e.Status != 0 {
		return fmt.Sprintf("TypeSafe %s (HTTP %d)", e.Reason, e.Status)
	}
	if e.Err != nil {
		return fmt.Sprintf("TypeSafe %s: %v", e.Reason, e.Err)
	}
	return "TypeSafe " + e.Reason
}
func (e *JevError) Unwrap() error { return e.Err }

// reasonOf renvoie la cause d'une erreur d'analyse, quelle que soit sa source.
func reasonOf(err error) string {
	var je *JevError
	switch {
	case errors.As(err, &je):
		return je.Reason
	case errors.Is(err, context.DeadlineExceeded):
		return ReasonTimeout
	case errors.Is(err, context.Canceled):
		return ReasonCancelled
	}
	var ne net.Error
	if errors.As(err, &ne) && ne.Timeout() {
		return ReasonTimeout
	}
	return ReasonNetwork
}

func statusReason(status int) string {
	switch {
	case status == 401 || status == 403:
		return ReasonAuth
	case status == 402 || status == 429:
		return ReasonQuota
	case status >= 500:
		return ReasonServer
	}
	return ReasonRejected
}

const typesafeEndpoint = "https://api.typesafe.ai/v1/systemone"
const question = "Is this image generated by artificial intelligence?"

type Estimate struct {
	Value float64
	Model string
}
type Analyzer interface {
	Analyze(context.Context, []byte) (Estimate, error)
}
type TypeSafe struct {
	Key, Model, Endpoint string
	HTTP                 *http.Client
}

func (c *TypeSafe) Analyze(ctx context.Context, data []byte) (Estimate, error) {
	// Only normalized pixels and a new opaque reference leave the server.
	ref := token()
	body := map[string]any{
		"model":     c.Model,
		"state":     map[string]string{"image": ref},
		"assets":    map[string]any{ref: map[string]string{"type": "image", "format": "jpg", "data_base64": base64.StdEncoding.EncodeToString(data)}},
		"questions": map[string]any{"generated": map[string]string{"type": "noul", "instructions": question}},
	}
	raw, err := json.Marshal(body)
	if err != nil {
		return Estimate{}, err
	}
	req, err := http.NewRequestWithContext(ctx, "POST", c.Endpoint, bytes.NewReader(raw))
	if err != nil {
		return Estimate{}, err
	}
	req.Header.Set("Authorization", "Bearer "+c.Key)
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("TypeSafe-Danger-Zone-Images", "true")
	resp, err := c.HTTP.Do(req)
	if err != nil {
		if r := reasonOf(err); r == ReasonTimeout || r == ReasonCancelled {
			return Estimate{}, &JevError{Reason: r, Err: err}
		}
		return Estimate{}, &JevError{Reason: ReasonNetwork, Err: err}
	}
	defer resp.Body.Close()
	// Never log the provider body, which could echo request data or credentials.
	if resp.StatusCode != http.StatusOK {
		return Estimate{}, &JevError{Reason: statusReason(resp.StatusCode), Status: resp.StatusCode}
	}
	var result struct {
		Model   string `json:"model"`
		Answers map[string]struct {
			Type string   `json:"type"`
			Noul *float64 `json:"noul"`
		} `json:"answers"`
	}
	if err := json.NewDecoder(io.LimitReader(resp.Body, 1<<20)).Decode(&result); err != nil {
		if r := reasonOf(err); r == ReasonTimeout || r == ReasonCancelled {
			return Estimate{}, &JevError{Reason: r, Err: err}
		}
		return Estimate{}, &JevError{Reason: ReasonInvalid, Err: fmt.Errorf("JSON illisible: %w", err)}
	}
	a, ok := result.Answers["generated"]
	if !ok || a.Type != "noul" || a.Noul == nil || math.IsNaN(*a.Noul) || math.IsInf(*a.Noul, 0) || *a.Noul < 0 || *a.Noul > 1 || result.Model == "" {
		return Estimate{}, &JevError{Reason: ReasonInvalid, Err: errors.New("réponse Noul manquante ou invalide")}
	}
	return Estimate{*a.Noul, result.Model}, nil
}

// -1 means abstention: exactly equal estimates must not break a tie.
func selectJev(a, b float64) int {
	if a == b {
		return -1
	}
	if a > b {
		return 0
	}
	return 1
}
