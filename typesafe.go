package main

import (
	"bytes"
	"context"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"io"
	"math"
	"net/http"
)

const typesafeEndpoint = "https://api.typesafe.ai/v1/systemone"
const question = "Is this image generated by artificial intelligence?"

type Estimate struct {
	Value float64
	Model string
}
type Analyzer interface {
	Analyze(context.Context, []byte) (Estimate, error)
}
type TypeSafe struct {
	Key, Model, Endpoint string
	HTTP                 *http.Client
}

func (c *TypeSafe) Analyze(ctx context.Context, data []byte) (Estimate, error) {
	// Only normalized pixels and a new opaque reference leave the server.
	ref := token()
	body := map[string]any{
		"model":     c.Model,
		"state":     map[string]string{"image": ref},
		"assets":    map[string]any{ref: map[string]string{"type": "image", "format": "jpg", "data_base64": base64.StdEncoding.EncodeToString(data)}},
		"questions": map[string]any{"generated": map[string]string{"type": "noul", "instructions": question}},
	}
	raw, err := json.Marshal(body)
	if err != nil {
		return Estimate{}, err
	}
	req, err := http.NewRequestWithContext(ctx, "POST", c.Endpoint, bytes.NewReader(raw))
	if err != nil {
		return Estimate{}, err
	}
	req.Header.Set("Authorization", "Bearer "+c.Key)
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("TypeSafe-Danger-Zone-Images", "true")
	resp, err := c.HTTP.Do(req)
	if err != nil {
		return Estimate{}, fmt.Errorf("transport TypeSafe: %w", err)
	}
	defer resp.Body.Close()
	// Never log the provider body, which could echo request data or credentials.
	if resp.StatusCode != http.StatusOK {
		return Estimate{}, fmt.Errorf("TypeSafe HTTP %d", resp.StatusCode)
	}
	var result struct {
		Model   string `json:"model"`
		Answers map[string]struct {
			Type string   `json:"type"`
			Noul *float64 `json:"noul"`
		} `json:"answers"`
	}
	if err := json.NewDecoder(io.LimitReader(resp.Body, 1<<20)).Decode(&result); err != nil {
		return Estimate{}, fmt.Errorf("réponse TypeSafe invalide: %w", err)
	}
	a, ok := result.Answers["generated"]
	if !ok || a.Type != "noul" || a.Noul == nil || math.IsNaN(*a.Noul) || math.IsInf(*a.Noul, 0) || *a.Noul < 0 || *a.Noul > 1 || result.Model == "" {
		return Estimate{}, fmt.Errorf("réponse Noul manquante ou invalide")
	}
	return Estimate{*a.Noul, result.Model}, nil
}

// -1 means abstention: exactly equal estimates must not break a tie.
func selectJev(a, b float64) int {
	if a == b {
		return -1
	}
	if a > b {
		return 0
	}
	return 1
}
